//! 匯出「重建清單」：把目前盤點結果寫成一包可直接使用的檔案。
//! 全部寫在使用者 Downloads 底下的一個時間戳資料夾，不覆蓋任何既有檔案。

use crate::models::{Inventory, Item};
use crate::scan::now_ms;
use crate::sh;
use serde::Serialize;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::time::Duration;

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ExportResult {
    pub folder: String,
    pub files: Vec<String>,
    pub item_count: usize,
}

fn base_dir() -> PathBuf {
    let home = sh::home();
    let downloads = PathBuf::from(&home).join("Downloads");
    if downloads.is_dir() {
        downloads
    } else {
        PathBuf::from(home)
    }
}

fn stamp() -> String {
    let command = if cfg!(windows) {
        sh::run(
            "powershell",
            &[
                "-NoProfile",
                "-Command",
                "Get-Date -Format yyyy-MM-dd-HHmmss",
            ],
            Duration::from_secs(15),
        )
    } else {
        sh::run("date", &["+%Y-%m-%d-%H%M%S"], Duration::from_secs(10))
    };
    command
        .ok()
        .map(|out| out.stdout.trim().to_string())
        .filter(|text| !text.is_empty())
        .unwrap_or_else(|| format!("{}", now_ms() / 1000))
}

fn safe_name(text: &str) -> String {
    let mapped: String = text
        .chars()
        .map(|c| if c.is_alphanumeric() || c == '.' { c } else { '-' })
        .collect();
    // 收斂連續的 '-' 並去掉頭尾
    let mut out = String::with_capacity(mapped.len());
    for c in mapped.chars() {
        if c == '-' && out.ends_with('-') {
            continue;
        }
        out.push(c);
    }
    out.trim_matches('-').to_string()
}

fn items_of<'a>(inventory: &'a Inventory, ecosystem: &str) -> Vec<&'a Item> {
    inventory
        .ecosystems
        .iter()
        .filter(|eco| eco.id == ecosystem)
        .flat_map(|eco| eco.items.iter())
        .collect()
}

/// 各語言的標題與指令說明（REBUILD.md 用）
struct Words {
    title: String,
    scanned: &'static str,
    files: &'static str,
    file: &'static str,
    purpose: &'static str,
    rebuild: &'static str,
    counts: &'static str,
    note: &'static str,
}

fn words(lang: &str) -> Words {
    match lang {
        "en" => Words {
            title: String::from("# Rebuild list"),
            scanned: "Scanned",
            files: "## Files",
            file: "File",
            purpose: "Purpose",
            rebuild: "## Rebuild commands",
            counts: "## Inventory",
            note: "Generated by Envtally. Read-only tool: nothing here was installed by it.",
        },
        "zh-CN" => Words {
            title: String::from("# 重建清单"),
            scanned: "扫描时间",
            files: "## 文件",
            file: "文件",
            purpose: "用途",
            rebuild: "## 重建指令",
            counts: "## 清单",
            note: "由 Envtally 生成。只读工具：它没有安装或修改任何东西。",
        },
        _ => Words {
            title: String::from("# 重建清單"),
            scanned: "掃描時間",
            files: "## 檔案",
            file: "檔案",
            purpose: "用途",
            rebuild: "## 重建指令",
            counts: "## 清單",
            note: "由 Envtally 產生。只讀工具：它沒有安裝或修改任何東西。",
        },
    }
}

pub fn write_bundle(inventory: &Inventory, lang: &str) -> Result<ExportResult, String> {
    write_bundle_at(inventory, lang, &base_dir())
}

/// 指定根目錄的版本（測試用）。
pub fn write_bundle_at(
    inventory: &Inventory,
    lang: &str,
    base: &Path,
) -> Result<ExportResult, String> {
    let folder = base.join("Envtally").join(format!("export-{}", stamp()));
    std::fs::create_dir_all(&folder).map_err(|e| format!("建立資料夾失敗：{e}"))?;

    let mut files: Vec<String> = Vec::new();
    let mut write = |name: &str, content: String| -> Result<(), String> {
        let path = folder.join(name);
        std::fs::write(&path, content).map_err(|e| format!("寫入 {name} 失敗：{e}"))?;
        files.push(name.to_string());
        Ok(())
    };

    // ── Brewfile ──
    let brew = items_of(inventory, "brew");
    let mut brewfile = format!("# Envtally — {}\n", stamp());
    brewfile.push_str("# brew bundle install --file=Brewfile\n");
    for item in brew.iter().filter(|item| item.kind == "formula") {
        brewfile.push_str(&format!("brew \"{}\"\n", item.name));
    }
    for item in brew.iter().filter(|item| item.kind == "cask") {
        brewfile.push_str(&format!("cask \"{}\"\n", item.name));
    }
    if brew.iter().any(|item| item.kind == "formula" || item.kind == "cask") {
        write("Brewfile", brewfile)?;
    }

    // ── requirements-<python>.txt（每個直譯器一份）──
    let python = items_of(inventory, "python");
    let mut by_interp: BTreeMap<String, Vec<&Item>> = BTreeMap::new();
    for item in python.iter().filter(|item| item.kind == "package") {
        by_interp.entry(item.source.clone()).or_default().push(item);
    }
    for (source, packages) in &by_interp {
        let mut body = format!("# {source}\n");
        body.push_str(&format!(
            "# pip install -r requirements-{}.txt\n",
            safe_name(source)
        ));
        for package in packages {
            body.push_str(&format!("{}=={}\n", package.name, package.version));
        }
        write(&format!("requirements-{}.txt", safe_name(source)), body)?;
    }

    // ── npm 全域 ──
    let node_packages: Vec<&Item> = items_of(inventory, "node")
        .into_iter()
        .filter(|item| item.kind == "package")
        .collect();
    if !node_packages.is_empty() {
        let mut body = String::from("#!/bin/sh\n# Envtally — npm global packages\nset -e\nnpm install -g \\\n");
        for (index, package) in node_packages.iter().enumerate() {
            let sep = if index + 1 == node_packages.len() { "" } else { " \\\n" };
            body.push_str(&format!("  {}@{}{}", package.name, package.version, sep));
        }
        body.push('\n');
        write("npm-globals.sh", body)?;
    }

    // ── Ruby gems ──
    let gems: Vec<&Item> = items_of(inventory, "ruby")
        .into_iter()
        .filter(|item| item.kind == "gem")
        .collect();
    if !gems.is_empty() {
        let mut body = String::from("#!/bin/sh\n# Envtally — Ruby gems\nset -e\n");
        for gem in &gems {
            body.push_str(&format!("gem install {} -v {}\n", gem.name, gem.version));
        }
        write("gems.sh", body)?;
    }

    // ── .NET global.json ──
    if let Some(sdk) = items_of(inventory, "dotnet")
        .into_iter()
        .find(|item| item.kind == "sdk")
    {
        let body = format!(
            "{{\n  \"sdk\": {{\n    \"version\": \"{}\",\n    \"rollForward\": \"latestPatch\"\n  }}\n}}\n",
            sdk.version
        );
        write("global.json", body)?;
    }

    // ── REBUILD.md ──
    let text = words(lang);
    let mut md = format!("{}\n\n", text.title);
    md.push_str(&format!("- {}: {}\n", text.scanned, stamp()));
    md.push_str(&format!(
        "- {} · {} · {}\n\n",
        inventory.model, inventory.os, inventory.arch
    ));

    md.push_str(&format!("{}\n\n", text.counts));
    md.push_str(&format!("| {} | {} |\n|---|---|\n", text.file, text.purpose));
    for name in &files {
        let purpose = match name.as_str() {
            "Brewfile" => "Homebrew formula / cask",
            "npm-globals.sh" => "npm global packages",
            "gems.sh" => "Ruby gems",
            "global.json" => ".NET SDK version",
            _ if name.starts_with("requirements-") => "Python packages",
            _ => "",
        };
        md.push_str(&format!("| `{name}` | {purpose} |\n"));
    }

    md.push_str(&format!("\n{}\n\n", text.rebuild));
    if files.iter().any(|name| name == "Brewfile") {
        md.push_str("```sh\nbrew bundle install --file=Brewfile\n```\n\n");
    }
    for source in by_interp.keys() {
        md.push_str(&format!(
            "```sh\npip install -r requirements-{}.txt\n```\n\n",
            safe_name(source)
        ));
    }
    if files.iter().any(|name| name == "npm-globals.sh") {
        md.push_str("```sh\nsh npm-globals.sh\n```\n\n");
    }
    if files.iter().any(|name| name == "gems.sh") {
        md.push_str("```sh\nsh gems.sh\n```\n\n");
    }
    md.push_str(&format!("---\n\n{}\n", text.note));

    std::fs::write(folder.join("REBUILD.md"), md).map_err(|e| format!("寫入 REBUILD.md 失敗：{e}"))?;
    files.push(String::from("REBUILD.md"));

    let item_count = inventory
        .ecosystems
        .iter()
        .map(|eco| eco.items.len())
        .sum::<usize>();

    Ok(ExportResult {
        folder: folder.display().to_string(),
        files,
        item_count,
    })
}

/// 在 Finder 裡選取匯出的資料夾。
pub fn reveal(path: &str) -> Result<(), String> {
    let target = Path::new(path);
    if !target.exists() {
        return Err(String::from("路徑不存在"));
    }
    if cfg!(windows) {
        // explorer 對 /select 的參數格式要求較鬆，失敗時回非零碼
        sh::run(
            "explorer",
            &[&format!("/select,{path}")],
            Duration::from_secs(15),
        )
        .map(|_| ())
    } else if cfg!(target_os = "macos") {
        sh::run("open", &["-R", path], Duration::from_secs(15)).map(|_| ())
    } else {
        sh::run("xdg-open", &[path], Duration::from_secs(15)).map(|_| ())
    }
}
